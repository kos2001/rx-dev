const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:3030');
  await page.locator('#agentVideoSeed').waitFor({timeout:30000});
  assert.equal(await page.locator('#agentVideoSeed option').count(),10);
  assert.equal(await page.locator('#agentVideoSeed').inputValue(),'211');
  await page.waitForFunction(()=>document.getElementById('incumbentVideo').readyState>=2 && document.getElementById('candidateVideo').readyState>=2);
  assert.match(await page.locator('#agentVideoComparison').textContent(),/기존 설정만 성공/);
  await page.locator('#agentVideoPlay').click();
  await page.waitForFunction(()=>document.getElementById('incumbentVideo').currentTime>0.5 && document.getElementById('candidateVideo').currentTime>0.5);
  await page.locator('#agentVideoPlay').click();
  await page.locator('#agentVideoTime').fill('8');
  await page.waitForFunction(()=>Math.abs(document.getElementById('incumbentVideo').currentTime-8)<0.2 && Math.abs(document.getElementById('candidateVideo').currentTime-8)<0.2);
  await page.locator('#agentVideoSeed').selectOption('214');
  await page.waitForFunction(()=>document.getElementById('incumbentVideo').readyState>=2 && document.getElementById('candidateVideo').readyState>=2);
  assert.match(await page.locator('#agentVideoComparison').textContent(),/Agent 후보만 성공/);
  await page.locator('#agentVideoTime').fill('30');
  await page.waitForFunction(()=>!document.getElementById('incumbentVideo').seeking && !document.getElementById('candidateVideo').seeking && document.getElementById('candidateVideo').currentTime>15);
  await page.locator('.agent-recordings').screenshot({path:'outputs/dashboard/candidate-comparison.png'});
  const src=await page.locator('#candidateVideo').getAttribute('src');
  const response=await page.request.get(src,{headers:{Range:'bytes=0-99'}});
  assert.equal(response.status(),206);assert.equal((await response.body()).length,100);
  const loaded=await page.evaluate(()=>({old:document.getElementById('incumbentVideo').videoWidth,candidate:document.getElementById('candidateVideo').videoWidth}));
  assert.ok(loaded.old>0 && loaded.candidate>0);
  await page.setViewportSize({width:390,height:844});
  await page.locator('.agent-recordings').screenshot({path:'outputs/dashboard/candidate-comparison-mobile.png'});
  assert.ok(await page.evaluate(()=>document.body.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  await browser.close();console.log('PASS: 10 same-seed video pairs, actual decoding, simultaneous playback, shared seek, contrasting outcomes, media ranges, mobile layout');
})().catch(e=>{console.error(e);process.exit(1);});

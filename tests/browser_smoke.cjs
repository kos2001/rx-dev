// Run with Playwright available on NODE_PATH and both local servers running.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

(async () => {
  await fs.mkdir('outputs/dashboard', { recursive: true });
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:3030');
  await page.locator('#successRate').filter({ hasText: '30%' }).waitFor();
  await page.locator('#play:not(:disabled)').waitFor();
  assert.equal(await page.locator('#episodeRows tr').count(), 10);
  assert.equal(await page.locator('video').count(), 2);
  assert.equal(await page.locator('#connectionText').textContent(), '백엔드 연결됨');
  await page.locator('#seed').selectOption('102');
  await page.locator('#episodeRows tr[data-seed="102"].selected').waitFor();
  await page.locator('#timeline').fill('149');
  assert.match(await page.locator('#stepLabel').textContent(), /150/);
  await page.locator('#play').click();
  await page.waitForFunction(() => document.getElementById('timeline').value > 149);
  await page.locator('#play').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'outputs/dashboard/preview.png' });
  await page.screenshot({ path: 'outputs/dashboard/desktop.png', fullPage: true });
  await page.locator('[data-view="examples"]').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await page.locator('.example-card').count(), 7);
  assert.equal(await page.locator('[data-example]').count(), 3);
  await page.screenshot({ path: 'outputs/dashboard/examples.png', fullPage: true });
  // Start an actual backend simulation from the frontend and await its artifact.
  await page.locator('[data-example="transfer"]').click();
  await page.locator('#steps').fill('30');
  await page.locator('#run').click();
  await page.locator('#jobStatus').filter({ hasText: '완료' }).waitFor({ timeout: 90000 });
  assert.equal(await page.locator('#jobStatus').textContent(), '완료');
  await page.locator('#demoSummary').filter({ hasText: 'AlohaTransferCube-v0' }).waitFor();
  assert.equal(await page.locator('#agentView').isVisible(), false);
  assert.equal(await page.locator('video').count(), 1);
  await page.screenshot({ path: 'outputs/dashboard/transfer.png', fullPage: true });
  await page.locator('#experiment').selectOption('pusht-agent');
  await page.locator('#mode').selectOption('quick');
  await page.locator('#steps').fill('20');
  await page.locator('#run').click();
  await page.locator('#jobTitle').filter({ hasText: 'PushT' }).waitFor();
  await page.locator('#jobStatus').filter({ hasText: '완료' }).waitFor({ timeout: 90000 });
  await page.locator('#resultKind').filter({ hasText: '빠른 확인' }).waitFor();
  await page.locator('#play:not(:disabled)').waitFor();
  assert.equal(await page.locator('#episodeRows tr').count(), 1);
  await page.locator('#reportSelect').selectOption('agent');
  await page.locator('#successRate').filter({ hasText: '30%' }).waitFor();
  await page.locator('#play:not(:disabled)').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'outputs/dashboard/mobile.png', fullPage: true });
  const width = await page.evaluate(() => ({ viewport: innerWidth, body: document.body.scrollWidth }));
  assert.ok(width.body <= width.viewport, `Mobile page overflow: ${JSON.stringify(width)}`);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: metrics, seed selection, playback, examples, real ALOHA and PushT API jobs, demo result, mobile layout, no JS errors');
})().catch(error => { console.error(error); process.exit(1); });
